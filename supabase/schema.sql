-- Little Learners — Supabase schema.
-- Run this once in the Supabase dashboard: SQL Editor → New query → paste → Run.
--
-- Families sign in as a grown-up (Supabase Auth). Every row belongs to that
-- grown-up (parent_id = auth.uid()), and row-level security makes sure a
-- family can only ever read or change its own rows.
-- Children are stored with a first name / nickname and an avatar only.

-- ------------------------------------------------------------------ children
create table if not exists public.children (
  id           text primary key,                 -- generated by the app
  parent_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name         text not null check (char_length(name) between 1 and 40),
  avatar       text not null,
  color_index  int  not null default 0,
  level        text not null,                    -- age2 … grade5
  adjust       jsonb not null default '{}'::jsonb, -- adaptive difficulty per subject
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists children_parent_idx on public.children(parent_id);

-- ------------------------------------------------------------------- results
-- One row per finished worksheet.
create table if not exists public.results (
  id            text primary key,                -- generated by the app (idempotent uploads)
  parent_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  child_id      text not null references public.children(id) on delete cascade,
  worksheet_id  text not null,                   -- e.g. 20261120_addition
  kind          text not null,                   -- worksheet kind, e.g. addition
  category      text,                            -- math, reading, science, puzzles, writing (null = learning quiz)
  level         text not null,                   -- difficulty it was played at
  stars         int  not null check (stars between 0 and 3),
  questions     int  not null default 0,
  mistakes      int  not null default 0,
  seconds       int  not null default 0,
  completed_at  timestamptz not null
);
create index if not exists results_child_idx on public.results(child_id, completed_at desc);

-- ---------------------------------------------------------------------- seen
-- Fingerprints of questions a child has seen (so they aren't repeated soon).
create table if not exists public.seen (
  child_id     text not null references public.children(id) on delete cascade,
  parent_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  fingerprint  text not null,
  day          int  not null,                    -- days since 2024-01-01
  primary key (child_id, fingerprint)
);

-- ------------------------------------------------------- row-level security
alter table public.children enable row level security;
alter table public.results  enable row level security;
alter table public.seen     enable row level security;

drop policy if exists "own children" on public.children;
create policy "own children" on public.children
  for all using (parent_id = auth.uid()) with check (parent_id = auth.uid());

drop policy if exists "own results" on public.results;
create policy "own results" on public.results
  for all using (parent_id = auth.uid()) with check (parent_id = auth.uid());

drop policy if exists "own seen" on public.seen;
create policy "own seen" on public.seen
  for all using (parent_id = auth.uid()) with check (parent_id = auth.uid());

-- Keep updated_at fresh on edits.
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

drop trigger if exists children_touch on public.children;
create trigger children_touch before update on public.children
  for each row execute function public.touch_updated_at();

-- Signed-in grown-ups may use the tables (row-level security above still
-- limits them to their own rows). Anonymous visitors get nothing.
grant select, insert, update, delete on public.children, public.results, public.seen to authenticated;
revoke all on public.children, public.results, public.seen from anon;

-- ------------------------------------------------------- account deletion
-- Lets a signed-in grown-up delete their own account. Deleting the auth user
-- removes all of the family's children, results and seen rows (on delete
-- cascade). Runs with elevated rights, but only ever touches auth.uid().
create or replace function public.delete_my_account() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then
    raise exception 'not signed in';
  end if;
  delete from auth.users where id = auth.uid();
end $$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
