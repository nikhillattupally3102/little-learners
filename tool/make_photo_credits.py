"""Generates the photo credits used by the app and the website.

Usage: python3 -I tool/make_photo_credits.py
Reads  tool/photos/credits.json  (written by tool/fetch_photos.py)
Writes lib/content/photo_credits.dart  and  web/credits.html
"""
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
credits = json.load(open(os.path.join(ROOT, 'tool', 'photos', 'credits.json')))

# Letters show the photo of their example word, when we have one.
LETTER_PHOTO = {
    'A': 'fruits__apple', 'C': 'farm__cat', 'D': 'farm__dog', 'F': 'ocean__fish',
    'G': 'fruits__grapes', 'L': 'wild__lion', 'M': 'wild__monkey',
    'O': 'ocean__octopus', 'P': 'farm__pig', 'S': 'space__sun', 'T': 'wild__tiger',
    'W': 'fruits__watermelon', 'Z': 'wild__zebra',
}


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', ' ') + "'"


keys = sorted(credits)
for k in keys:
    assert os.path.exists(os.path.join(ROOT, 'assets', 'photos', k + '.jpg')), k

lines = []
for k in keys:
    c = credits[k]
    lines.append(
        f"  {dart(k)}: PhotoCredit({dart(c['artist'][:120])}, {dart(c['license'])}, "
        f"{dart(c['source'])}, {dart(c.get('article') or c['name'])}),"
    )
letters = '\n'.join(f"  {dart(l)}: {dart(k)}," for l, k in LETTER_PHOTO.items() if k in credits)

out = f"""// GENERATED by tool/make_photo_credits.py — do not edit by hand.
// Real-life photos from Wikipedia / Wikimedia Commons shown next to the
// drawings in learning sessions. Every photo is public domain, CC0, CC BY
// or CC BY-SA; the credit below is shown in the app and on /credits.

class PhotoCredit {{
  const PhotoCredit(this.artist, this.license, this.source, this.subject);
  final String artist;
  final String license;

  /// The photo's page on Wikimedia Commons.
  final String source;

  /// What the photo shows (e.g. "Taj Mahal" for India).
  final String subject;
}}

/// Photo id (`topic__item`, also the file name in assets/photos) → credit.
const photoCredits = <String, PhotoCredit>{{
{chr(10).join(lines)}
}};

/// Letters reuse the photo of their example word (A is for apple).
const letterPhotos = <String, String>{{
{letters}
}};
"""
open(os.path.join(ROOT, 'lib', 'content', 'photo_credits.dart'), 'w').write(out)

# ---------------------------------------------------------------- website
rows = ''.join(
    f"<tr><td>{html.escape(credits[k]['name'])}</td><td>{html.escape(credits[k].get('article') or '')}</td>"
    f"<td>{html.escape(credits[k]['artist'][:120])}</td>"
    f"<td><a href=\"{html.escape(credits[k]['license_url'] or credits[k]['source'])}\">{html.escape(credits[k]['license'])}</a></td>"
    f"<td><a href=\"{html.escape(credits[k]['source'])}\">Wikimedia Commons</a></td></tr>"
    for k in keys
)
page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Little Learners — Photo credits</title>
<style>
  :root {{ --ink:#2D2A4A; --muted:#5d5a78; --bg:#FFF8EC; --card:#fff; --accent:#4FA8F0; }}
  body {{ margin:0; background:var(--bg); color:var(--ink); font:16px/1.55 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; }}
  main {{ max-width: 980px; margin: 0 auto; padding: 32px 16px 64px; }}
  .card {{ background:var(--card); border-radius:24px; padding:24px; box-shadow:0 4px 16px rgba(0,0,0,.06); }}
  h1 {{ font-size:28px; margin:0 0 8px; }}
  .wrap {{ overflow-x:auto; }}
  table {{ border-collapse:collapse; width:100%; font-size:14px; }}
  th, td {{ text-align:left; padding:7px 9px; border-bottom:1px solid #eee; vertical-align:top; }}
  th {{ color:var(--muted); font-weight:600; }}
  a {{ color:var(--accent); }}
</style>
</head>
<body>
<main><div class="card">
<h1>Photo credits</h1>
<p>The real-life photos in Little Learners' learning sessions come from
<a href="https://commons.wikimedia.org">Wikimedia Commons</a>. Thank you to
every photographer. Each photo is used under the licence shown; photos were
resized for the app. See also our <a href="privacy.html">privacy policy</a>.</p>
<div class="wrap"><table>
<tr><th>Item</th><th>Photo of</th><th>Photographer</th><th>Licence</th><th>Source</th></tr>
{rows}
</table></div>
</div></main>
</body>
</html>
"""
open(os.path.join(ROOT, 'web', 'credits.html'), 'w').write(page)
print(len(keys), 'photo credits;', len(LETTER_PHOTO), 'letter photos')
